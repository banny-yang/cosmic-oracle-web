/** 拉已发布文章（发布时间倒序），供 llms 清单与 RSS feed 共用；接口不可用回落空。 */
export async function fetchPublishedArticles(limit: number): Promise<LlmsArticleRow[]> {
  const base = runtimeApiBaseUrl() || import.meta.env["VITE_API_BASE_URL"] || "";
  if (!base) return [];
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 5000);
  try {
    const res = await fetch(`${base}/api/v1/articles?page=0&size=${limit}`, {
      signal: controller.signal,
      headers: { accept: "application/json" },
    });
    if (!res.ok) return [];
    const body = (await res.json()) as { items?: LlmsArticleRow[] | null };
    return body.items ?? [];
  } catch {
    return [];
  } finally {
    clearTimeout(timer);
  }
}

function articleBlock(rows: LlmsArticleRow[], heading: string): string {
  if (!rows.length) return "";
  const lines = rows.map(
    (a) => `- 《${a.title}》 https://name.duimai.net/articles/${a.slug} ：${a.summary}`,
  );
  return `${heading}（共 ${rows.length} 篇）\n\n${lines.join("\n")}\n`;
}

function inject(staticText: string, block: string): string {
  return staticText.replace(ARTICLES_PLACEHOLDER, block).replace(/\n{3,}/g, "\n\n");
}

export async function llmsTxt(): Promise<string> {
  const rows = await fetchPublishedArticles(50);
  return inject(LLMS_TXT, articleBlock(rows, "## 深度洞察文章逐篇"));
}

